# Map our color hex to pgfplots-friendly names
_PGFCOLORS = [
    "{rgb,255:red,31;green,119;blue,180}",   # #1f77b4
    "{rgb,255:red,214;green,39;blue,40}",     # #d62728
    "{rgb,255:red,44;green,160;blue,44}",     # #2ca02c
    "{rgb,255:red,255;green,127;blue,14}",    # #ff7f0e
    "{rgb,255:red,148;green,103;blue,189}",   # #9467bd
    "{rgb,255:red,140;green,86;blue,75}",     # #8c564b
    "{rgb,255:red,227;green,119;blue,194}",   # #e377c2
    "{rgb,255:red,127;green,127;blue,127}",   # #7f7f7f
]


def _hex_to_pgf(hex_color: str) -> str:
    """Convert a #rrggbb hex string to a pgfplots rgb color expression."""
    h = hex_color.lstrip("#")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return f"{{rgb,255:red,{r};green,{g};blue,{b}}}"

_PGFMARKS = ["*", "square*", "triangle*", "diamond*", "pentagon*", "star"]


def _scale_opt(scale: AxisScale) -> str:
    if scale == AxisScale.LOG:
        return "log"
    return "normal"


def _tikz_line_chart(
    data: list[dict],
    metric: str,
    viz: Visualization,
    x_label: str,
    y_label: str,
    csv_relpath: str,
    series_label: str | None = None,
    y_limits: tuple[float, float] | None = None,
    baseline: str | None = None,
) -> str:
    series_data = _group_by_series(data, metric)
    series_names = list(series_data.keys())
    color_map = assign_series_colors(series_names, baseline)

    # Define colors
    color_defs = []
    for i, name in enumerate(series_names):
        safe = name.replace(" ", "").replace("(", "").replace(")", "")
        pgf = _hex_to_pgf(color_map.get(name, COLORS[i % len(COLORS)]))
        color_defs.append(f"  \\definecolor{{color{safe}}}{pgf}")

    plots = []
    for i, name in enumerate(series_names):
        safe = name.replace(" ", "").replace("(", "").replace(")", "")
        mark = _PGFMARKS[i % len(_PGFMARKS)]
        plots.append(
            f"    \\addplot[color=color{safe}, mark={mark}, thick]\n"
            f"      table[x=x, y={metric}, col sep=comma] {{{csv_relpath}}};\n"  # filtered below
            f"    \\addlegendentry{{{name}}}"
        )

    # For pgfplots with multiple series in one CSV, we need per-series CSVs
    # or use a filter. Simpler: one CSV per series referenced via \\addplot table.
    # We'll generate the tikz to reference the shared CSV but with a filter.
    plots_filtered = []
    for i, name in enumerate(series_names):
        safe = name.replace(" ", "").replace("(", "").replace(")", "")
        mark = _PGFMARKS[i % len(_PGFMARKS)]
        # pgfplots can't filter CSV natively in a simple way, so we use
        # multiple table reads with discard-if-not.
        # Simpler approach: reference the CSV and let the user customize.
        # For now, generate separate \addplot commands with coordinates.
        points = series_data[name]
        x_sorted = _sort_x_numeric([p[0] for p in points])
        val_map = {p[0]: p[1] for p in points}
        coords = " ".join(f"({x},{val_map[x]})" for x in x_sorted)
        plots_filtered.append(
            f"    \\addplot[color=color{safe}, mark={mark}, thick]\n"
            f"      coordinates {{{coords}}};\n"
            f"    \\addlegendentry{{{name}}}"
        )

    x_mode = "log, log basis x=2," if viz.x_scale == AxisScale.LOG else ""
    y_mode = "ymode=log," if viz.y_scale == AxisScale.LOG else ""
    legend = viz.legend_position or "north west"
    legend_title = f"  legend style={{title={{{series_label}}}}},\n" if series_label else ""
    y_lim_opts = f"  ymin={y_limits[0]}, ymax={y_limits[1]},\n" if y_limits else ""

    return (
        "% Generated by piparse-bench\n"
        "\\begin{tikzpicture}\n"
        + "\n".join(color_defs) + "\n"
        "\\begin{axis}[\n"
        f"  xlabel={{{x_label}}},\n"
        f"  ylabel={{{y_label}}},\n"
        f"  {x_mode}\n"
        f"  {y_mode}\n"
        + y_lim_opts
        + f"  legend pos={legend},\n"
        + legend_title
        + "  grid=major,\n"
        "  grid style={dashed, gray!30},\n"
        "  thick,\n"
        "]\n"
        + "\n".join(plots_filtered) + "\n"
        "\\end{axis}\n"
        "\\end{tikzpicture}\n"
    )


def _tikz_bar_chart(
    data: list[dict],
    metric: str,
    viz: Visualization,
    x_label: str,
    y_label: str,
    csv_relpath: str,
    series_label: str | None = None,
    y_limits: tuple[float, float] | None = None,
    baseline: str | None = None,
) -> str:
    series_data = _group_by_series(data, metric)
    if series_data:
        series_name, points = next(iter(series_data.items()))
    else:
        series_name, points = None, []

    x_labels = _sort_x_numeric([p[0] for p in points])
    val_map = {p[0]: p[1] for p in points}
    coords = " ".join(f"({x},{val_map[x]})" for x in x_labels)
    symbolic = ", ".join(x_labels)

    y_mode = "ymode=log," if viz.y_scale == AxisScale.LOG else ""
    y_lim_opts = f"  ymin={y_limits[0]}, ymax={y_limits[1]},\n" if y_limits else ""

    is_baseline = series_name is not None and series_name == baseline
    color_def = (
        f"  \\definecolor{{barcolor}}{_hex_to_pgf(BASELINE_COLOR)}\n"
        if is_baseline else ""
    )
    plot_style = "[fill=barcolor, draw=barcolor]" if is_baseline else ""

    return (
        "% Generated by piparse-bench\n"
        "\\begin{tikzpicture}\n"
        + color_def
        + "\\begin{axis}[\n"
        "  ybar,\n"
        f"  xlabel={{{x_label}}},\n"
        f"  ylabel={{{y_label}}},\n"
        f"  symbolic x coords={{{symbolic}}},\n"
        "  xtick=data,\n"
        f"  {y_mode}\n"
        + y_lim_opts
        + "  nodes near coords,\n"
        "  nodes near coords align={vertical},\n"
        "  every node near coord/.append style={font=\\scriptsize},\n"
        "  bar width=15pt,\n"
        "  grid=major,\n"
        "  grid style={dashed, gray!30},\n"
        "]\n"
        f"  \\addplot{plot_style} coordinates {{{coords}}};\n"
        "\\end{axis}\n"
        "\\end{tikzpicture}\n"
    )


def _tikz_grouped_bar(
    data: list[dict],
    metric: str,
    viz: Visualization,
    x_label: str,
    y_label: str,
    csv_relpath: str,
    series_label: str | None = None,
    y_limits: tuple[float, float] | None = None,
    baseline: str | None = None,
) -> str:
    series_data = _group_by_series(data, metric)
    series_names = list(series_data.keys())
    color_map = assign_series_colors(series_names, baseline)

    all_x = set()
    for points in series_data.values():
        all_x.update(p[0] for p in points)
    x_labels = _sort_x_numeric(list(all_x))
    symbolic = ", ".join(x_labels)

    color_defs = []
    for i, name in enumerate(series_names):
        safe = name.replace(" ", "").replace("(", "").replace(")", "")
        pgf = _hex_to_pgf(color_map.get(name, COLORS[i % len(COLORS)]))
        color_defs.append(f"  \\definecolor{{color{safe}}}{pgf}")

    plots = []
    for i, name in enumerate(series_names):
        safe = name.replace(" ", "").replace("(", "").replace(")", "")
        val_map = {p[0]: p[1] for p in series_data[name]}
        coords = " ".join(f"({x},{val_map.get(x, 0)})" for x in x_labels)
        plots.append(
            f"  \\addplot[fill=color{safe}] coordinates {{{coords}}};\n"
            f"  \\addlegendentry{{{name}}}"
        )

    y_mode = "ymode=log," if viz.y_scale == AxisScale.LOG else ""
    legend = viz.legend_position or "north west"
    legend_title = f"  legend style={{title={{{series_label}}}}},\n" if series_label else ""
    y_lim_opts = f"  ymin={y_limits[0]}, ymax={y_limits[1]},\n" if y_limits else ""

    return (
        "% Generated by piparse-bench\n"
        "\\begin{tikzpicture}\n"
        + "\n".join(color_defs) + "\n"
        "\\begin{axis}[\n"
        "  ybar,\n"
        f"  xlabel={{{x_label}}},\n"
        f"  ylabel={{{y_label}}},\n"
        f"  symbolic x coords={{{symbolic}}},\n"
        "  xtick=data,\n"
        f"  {y_mode}\n"
        + y_lim_opts
        + f"  legend pos={legend},\n"
        + legend_title
        + "  grid=major,\n"
        "  grid style={dashed, gray!30},\n"
        "  bar width=10pt,\n"
        "]\n"
        + "\n".join(plots) + "\n"
        "\\end{axis}\n"
        "\\end{tikzpicture}\n"
    )


def _tikz_heatmap(
    data: list[dict],
    metric: str,
    viz: Visualization,
    x_label: str,
    y_label: str,
    csv_relpath: str,
    series_label: str | None = None,
    y_limits: tuple[float, float] | None = None,
    baseline: str | None = None,
) -> str:
    # Parse compound x_values
    points = [(row["x_value"], row.get(metric)) for row in data if row.get(metric) is not None]
    xs_set, ys_set = set(), set()
    values: dict[tuple[str, str], float] = {}
    for label, val in points:
        parts = label.split(" / ", 1)
        a, b = (parts[0], parts[1]) if len(parts) == 2 else (label, "")
        xs_set.add(a)
        ys_set.add(b)
        values[(a, b)] = val

    x_labels = sorted(xs_set)
    y_labels = sorted(ys_set)

    # Generate matrix data for pgfplots matrix plot
    rows = []
    for yl in y_labels:
        for xl in x_labels:
            v = values.get((xl, yl), 0)
            rows.append(f"    {xl} {yl} {v}")

    val_label = viz.value_label or metric
    hm_x_label = viz.x_label or x_label
    hm_y_label = viz.y_label or y_label

    return (
        "% Generated by piparse-bench\n"
        "% Heatmap — consider customizing colormap and cell annotations\n"
        "\\begin{tikzpicture}\n"
        "\\begin{axis}[\n"
        "  colorbar,\n"
        f"  colorbar style={{ylabel={{{val_label}}}}},\n"
        f"  xlabel={{{hm_x_label}}},\n"
        f"  ylabel={{{hm_y_label}}},\n"
        "  view={0}{90},\n"
        "]\n"
        "  \\addplot[matrix plot*, point meta=explicit]\n"
        "    coordinates {\n"
        + "\n".join(rows) + "\n"
        "    };\n"
        "\\end{axis}\n"
        "\\end{tikzpicture}\n"
    )


_TIKZ_RENDERERS = {
    ChartType.LINE_CHART: _tikz_line_chart,
    ChartType.BAR_CHART: _tikz_bar_chart,
    ChartType.GROUPED_BAR: _tikz_grouped_bar,
    ChartType.HEATMAP: _tikz_heatmap,
}


def render_tikz(
    data: list[dict],
    metric: str,
    viz: Visualization,
    x_label: str,
    y_label: str,
    output_path: Path,
    data_csv_path: Path | None = None,
    series_label: str | None = None,
    y_limits: tuple[float, float] | None = None,
    baseline: str | None = None,
) -> Path:
    """Render a .tikz file. Also writes the companion data CSV."""
    csv_path = data_csv_path or output_path.with_name(output_path.stem + "_data.csv")
    _write_data_csv(csv_path, data, metric)
    csv_relpath = csv_path.name

    renderer = _TIKZ_RENDERERS.get(viz.type)
    if renderer is None:
        raise ValueError(f"No TikZ renderer for chart type: {viz.type}")

    tikz_content = renderer(
        data, metric, viz, x_label, y_label, csv_relpath,
        series_label=series_label, y_limits=y_limits, baseline=baseline,
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(tikz_content)
    return output_path
